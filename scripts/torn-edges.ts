// Writes app/torn.css: the outlines of torn sheets of paper, as clip-path
// polygons that fit any size. Along each edge a point is a percentage, so it
// follows the sheet's length; across it, a few px, so the tear's depth stays
// the same on a phone and a wide screen. Slow swells and fine jags, the way
// paper tears. Run once and commit; the outlines never change.

import { writeFileSync } from "node:fs";

function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** The depth of the tear at step i of an edge, in px. */
function edge(r: () => number, n: number, depth: number) {
  const p1 = r() * 6;
  const p2 = r() * 6;
  return Array.from({ length: n + 1 }, (_, i) => {
    const slow = Math.sin(i * 0.31 + p1) * 0.45 + Math.sin(i * 0.83 + p2) * 0.3;
    const jag = (r() - 0.5) * 0.9;
    return Math.max(0.4, depth * (0.55 + slow + jag * 0.8));
  });
}

const n1 = (v: number) => Math.round(v * 10) / 10;

function polygon(seed: number) {
  const r = rng(seed);
  const top = edge(r, 70, 6);
  const right = edge(r, 42, 4.5);
  const bottom = edge(r, 70, 7);
  const left = edge(r, 42, 4.5);
  const pts: string[] = [];
  top.forEach((d, i) => pts.push(`${n1((i / 70) * 100)}% ${n1(d)}px`));
  right.forEach((d, i) => pts.push(`calc(100% - ${n1(d)}px) ${n1((i / 42) * 100)}%`));
  bottom.forEach((d, i) => pts.push(`${n1(100 - (i / 70) * 100)}% calc(100% - ${n1(d)}px)`));
  left.forEach((d, i) => pts.push(`${n1(d)}px ${n1(100 - (i / 42) * 100)}%`));
  return `polygon(${pts.join(",")})`;
}

const css = `/* Generated by scripts/torn-edges.ts: outlines of torn sheets. */\n:root {\n  --torn-a: ${polygon(11)};\n  --torn-b: ${polygon(29)};\n}\n`;
writeFileSync(new URL("../app/torn.css", import.meta.url), css);
console.log(`app/torn.css: ${css.length} bytes`);
